async function audit(page, label) {
  await page.addScriptTag({ content: axe })
  const result = await page.evaluate(async () => {
    const findings = await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa', 'wcag22aa'] } })
    return { violations: findings.violations.map(({ id, nodes }) => ({ id, nodes: nodes.map(({ html, failureSummary }) => ({ html, failureSummary })) })), incomplete: findings.incomplete.map(({ id, nodes }) => ({ id, nodes: nodes.map(({ html, failureSummary }) => ({ html, failureSummary })) })) }
  })
  results.push({ label, ...result })
}
